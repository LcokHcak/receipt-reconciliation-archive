const kids = [];
const P = (text, o = {}) => new Paragraph({
  spacing: { after: o.after ?? 120, before: o.before ?? 0 },
  alignment: o.align,
  children: [new TextRun({
    text, bold: o.bold, italics: o.italics, size: o.size ?? 21,
    color: o.color, font: '微软雅黑',
  })],
});
const H = (text, level) => new Paragraph({
  heading: level, spacing: { before: 260, after: 140 },
  children: [new TextRun({ text, font: '微软雅黑', bold: true })],
});
const rich = (runs, o = {}) => new Paragraph({
  spacing: { after: o.after ?? 120 },
  children: runs.map((r) => new TextRun({
    text: r.t, bold: r.b, color: r.c, size: r.s ?? 21, font: '微软雅黑',
  })),
});

function cell(text, o = {}) {
  return new TableCell({
    width: { size: o.w ?? 25, type: WidthType.PERCENTAGE },
    shading: o.head ? { type: ShadingType.CLEAR, fill: GRAY } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: String(text).split('\n').map((line) => new Paragraph({
      spacing: { after: 40 },
      children: [new TextRun({ text: line, bold: o.head || o.bold, size: 19, color: o.color, font: '微软雅黑' })],
    })),
  });
}
function table(rows, widths) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: 'BFBFBF' },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: 'BFBFBF' },
      left: { style: BorderStyle.SINGLE, size: 2, color: 'BFBFBF' },
      right: { style: BorderStyle.SINGLE, size: 2, color: 'BFBFBF' },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: 'D9D9D9' },
      insideVertical: { style: BorderStyle.SINGLE, size: 1, color: 'D9D9D9' },
    },
    rows: rows.map((r, i) => new TableRow({
      tableHeader: i === 0,
      children: r.map((c, j) => cell(c, { head: i === 0, w: widths?.[j] })),
    })),
  });
}

